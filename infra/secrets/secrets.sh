#!/usr/bin/env bash
# Numo9 secrets with SOPS + age (S-03-T03). See docs/security/secrets-runbook.md.
#
#   secrets.sh keygen <file>            new age key pair in <file> (mode 600); prints the public key
#   secrets.sh recipients               regenerate .sops.yaml from infra/secrets/recipients/*.txt
#   secrets.sh edit <env>               create/edit infra/secrets/<env>.sops.env in $EDITOR (decrypts in memory)
#   secrets.sh set <env> NAME           set one variable from stdin (no value in shell history)
#   secrets.sh updatekeys <env>         re-encrypt the data key for the current recipients
#   secrets.sh rotate <env>             new data key for the file (after removing a recipient)
#   secrets.sh decrypt <env> <out>      decrypt to <out> with mode 600 (deploy host; needs SOPS_AGE_KEY_FILE)
#   secrets.sh check                    every *.sops.env is encrypted; recipients are public keys only
#
# <env> is staging or prod. Requires sops >= 3.9 and age.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
SECRETS_DIR="${SECRETS_DIR:-$ROOT/infra/secrets}"
SOPS_CONFIG="${SOPS_CONFIG:-$ROOT/.sops.yaml}"
ENVIRONMENTS=(staging prod)

die() { printf 'secrets: %s\n' "$*" >&2; exit 1; }
need() { command -v "$1" >/dev/null 2>&1 || die "$1 is not installed"; }
env_file() {
  local env="$1"
  [[ " ${ENVIRONMENTS[*]} " == *" $env "* ]] || die "unknown environment '$env' (staging|prod)"
  printf '%s/%s.sops.env' "$SECRETS_DIR" "$env"
}
sops_() { sops --config "$SOPS_CONFIG" "$@"; }

recipients_of() {
  # Public keys of one environment, comments and blank lines removed.
  local file="$SECRETS_DIR/recipients/$1.txt"
  [[ -f "$file" ]] || return 0
  sed -e 's/#.*//' -e 's/[[:space:]]//g' "$file" | grep -v '^$' || true
}

cmd_keygen() {
  need age-keygen
  local file="${1:?usage: secrets.sh keygen <file>}"
  [[ -e "$file" ]] && die "$file exists; refusing to overwrite a key"
  mkdir -p "$(dirname "$file")"
  (umask 077 && age-keygen -o "$file" 2>/dev/null)
  chmod 600 "$file"
  age-keygen -y "$file"
}

cmd_recipients() {
  local env keys
  {
    echo "# Generated by infra/secrets/secrets.sh recipients from infra/secrets/recipients/*.txt"
    echo "# (S-03-T03). Edit the recipients files, not this file."
    echo "creation_rules:"
    for env in "${ENVIRONMENTS[@]}"; do
      keys="$(recipients_of "$env" | paste -sd, -)"
      echo "  - path_regex: (^|/)infra/secrets/${env}\\.sops\\.env\$"
      echo "    age: \"${keys}\""
    done
  } >"$SOPS_CONFIG"
  for env in "${ENVIRONMENTS[@]}"; do
    printf 'secrets: %s — %s recipient(s)\n' "$env" "$(recipients_of "$env" | wc -l | tr -d ' ')"
  done
}

cmd_edit() {
  need sops
  local file
  file="$(env_file "${1:?usage: secrets.sh edit <env>}")"
  if [[ ! -f "$file" ]]; then
    # First edit: start from the template (names only), encrypted straight away.
    (cd "$ROOT" && sops_ encrypt --filename-override "infra/secrets/$1.sops.env" \
      --input-type dotenv --output-type dotenv "$SECRETS_DIR/env.template") >"$file.tmp"
    mv "$file.tmp" "$file"
  fi
  local status=0
  (cd "$ROOT" && sops_ edit --input-type dotenv --output-type dotenv "$file") || status=$?
  # sops exits 200 when the file was saved unchanged.
  [[ $status == 0 || $status == 200 ]] || exit "$status"
}

cmd_set() {
  need sops
  local file name value
  file="$(env_file "${1:?usage: secrets.sh set <env> NAME}")"
  name="${2:?usage: secrets.sh set <env> NAME}"
  [[ "$name" =~ ^[A-Z][A-Z0-9_]*$ ]] || die "invalid variable name '$name'"
  [[ -f "$file" ]] || die "$file does not exist; run: secrets.sh edit $1"
  IFS= read -r value || true
  [[ "$value" != *$'\n'* ]] || die "value must be one line"
  # sops set takes a JSON value; json.dumps escapes quotes and backslashes.
  printf '%s' "$value" | python3 -c 'import json, sys; print(json.dumps(sys.stdin.read()))' \
    | (cd "$ROOT" && sops_ set --input-type dotenv --output-type dotenv --value-stdin "$file" "[\"$name\"]")
}

cmd_updatekeys() {
  need sops
  local file
  file="$(env_file "${1:?usage: secrets.sh updatekeys <env>}")"
  (cd "$ROOT" && sops_ updatekeys --yes --input-type dotenv "$file")
}

cmd_rotate() {
  need sops
  local file
  file="$(env_file "${1:?usage: secrets.sh rotate <env>}")"
  (cd "$ROOT" && sops_ rotate --in-place --input-type dotenv --output-type dotenv "$file")
}

cmd_decrypt() {
  need sops
  local env="${1:?usage: secrets.sh decrypt <env> <out>}" out="${2:?usage: secrets.sh decrypt <env> <out>}"
  local file
  file="${SOPS_FILE:-$(env_file "$env")}"
  [[ -f "$file" ]] || die "$file not found"
  [[ -n "${SOPS_AGE_KEY_FILE:-}" || -n "${SOPS_AGE_KEY:-}" ]] || die "set SOPS_AGE_KEY_FILE to this host's age key"
  local tmp
  tmp="$(mktemp "$(dirname "$out")/.secrets.XXXXXX")"
  chmod 600 "$tmp"
  if ! sops decrypt --input-type dotenv --output-type dotenv "$file" >"$tmp"; then
    rm -f "$tmp"
    die "could not decrypt $file (is this host's public key in recipients/$env.txt?)"
  fi
  mv "$tmp" "$out"
  chmod 600 "$out"
}

cmd_check() {
  python3 "$ROOT/tools/ci/check_secrets.py" "$ROOT"
}

case "${1:-}" in
  keygen | recipients | edit | set | updatekeys | rotate | decrypt | check)
    cmd="$1"
    shift
    "cmd_$cmd" "$@"
    ;;
  *) sed -n '2,15p' "$0" >&2; exit 2 ;;
esac
