"""F-02-T04 — parsers: OFX/QFX, QBO (Intuit header stripped), CSV (encoding and delimiter
sniffed), XLSX.

Acceptance: 5 fixture files per format parse to the expected lines
(``tests/fixtures/statements``, regenerated by ``generate.py``). Also: the format is recognised
from the content; a file that isn't a statement, a legacy ``.xls`` and an empty file are refused
with a message that says what to do; a 50,000-line OFX file parses in a few seconds (ofxparse
needed more than two minutes — see ``numo9.banking.statements.ofx``).
"""

from __future__ import annotations

import datetime as dt
import json
import time
from collections import Counter
from decimal import Decimal
from pathlib import Path
from typing import Any

import pytest

from numo9.banking.statements.errors import StatementError
from numo9.banking.statements.layout import Layout, RawLine
from numo9.banking.statements.parsers import parse_statement, sniff_delimiter
from numo9.banking.statements.source import FileStatementSource

FIXTURES = Path(__file__).parent / "fixtures" / "statements"
OLE = b"\xd0\xcf\x11\xe0\xa1\xb1\x1a\xe1"
EXPECTED: dict[str, Any] = json.loads((FIXTURES / "expected.json").read_text(encoding="utf-8"))


def as_json(line: RawLine) -> dict[str, Any]:
    return {
        "row": line.row,
        "date": line.date.isoformat() if line.date else None,
        "amount": f"{line.amount:.2f}" if line.amount is not None else None,
        "description": line.description,
        "payee": line.payee,
        "reference": line.reference,
        "fitid": line.fitid,
        "balance": f"{line.balance:.2f}" if line.balance is not None else None,
        "problems": [p.code for p in line.problems],
    }


def test_five_fixtures_per_format() -> None:
    counts = Counter(name.rsplit(".", 1)[1] for name in EXPECTED)
    assert counts == {"ofx": 5, "qfx": 5, "qbo": 5, "csv": 5, "xlsx": 5}
    assert {p.name for p in FIXTURES.iterdir()} >= set(EXPECTED)


@pytest.mark.parametrize("name", sorted(EXPECTED))
def test_fixture_parses_to_the_expected_lines(name: str) -> None:
    expected = EXPECTED[name]
    layout = Layout.from_dict(expected["layout"]) if "layout" in expected else None
    source = FileStatementSource((FIXTURES / name).read_bytes(), name, layout)
    assert source.format == expected["format"]
    if "encoding" in expected:
        assert source.parsed.encoding == expected["encoding"]
    if "delimiter" in expected:
        assert source.parsed.delimiter == expected["delimiter"]
    assert [as_json(line) for line in source.fetch_lines()] == expected["lines"]
    assert len(source.parsed.warnings) == expected.get("warnings", 0)
    for last4, lines in expected.get("last4", {}).items():
        other = FileStatementSource(source.data, name, last4=last4)
        assert [as_json(line) for line in other.fetch_lines()] == lines


def test_qbo_header_is_stripped_and_ofx_metadata_kept() -> None:
    parsed = parse_statement((FIXTURES / "intuit_header.qbo").read_bytes(), "intuit_header.qbo")
    assert parsed.format == "qbo" and parsed.account_id == "5678901" and parsed.currency == "CAD"
    card = parse_statement((FIXTURES / "creditcard.ofx").read_bytes(), "creditcard.ofx")
    assert card.account_id.endswith("9012")


def test_format_comes_from_the_content_not_the_name() -> None:
    ofx = (FIXTURES / "td_web.qfx").read_bytes()
    assert parse_statement(ofx, "statement.csv").format == "ofx"
    csv_data = (FIXTURES / "rbc_chequing.csv").read_bytes()
    assert parse_statement(csv_data, "statement.txt").format == "csv"


@pytest.mark.parametrize(
    ("data", "name", "code"),
    [
        (b"", "empty.csv", "banking.statement.file.empty"),
        (b" \r\n\r\n", "blank.csv", "banking.statement.file.empty"),
        (b"\xef\xbb\xbf", "bom.csv", "banking.statement.file.empty"),
        (
            b"\xd0\xcf\x11\xe0\xa1\xb1\x1a\xe1" + b"\x00" * 64,
            "old.xls",
            "banking.statement.file.legacy_xls",
        ),
        (b"MZ\x90\x00\x03\x00\x00\x00", "tool.csv", "banking.statement.file.type"),
        (b"PK\x03\x04not really a zip", "fake.xlsx", "banking.statement.file.unreadable"),
        (b"OFXHEADER:100\n\nno body", "broken.ofx", "banking.statement.file.no_statement"),
        (b"just,some,text\n", "nothing.qfx", "banking.statement.file.no_statement"),
    ],
)
def test_files_that_are_refused(data: bytes, name: str, code: str) -> None:
    with pytest.raises(StatementError) as refused:
        parse_statement(data, name)
    assert refused.value.code == code
    assert name in refused.value.text


def test_delimiter_sniffing_ignores_a_title_line() -> None:
    text = "Statement for account 1234, period June\nDate;Description;Amount\n2026-06-03;A, B;-1\n"
    assert sniff_delimiter(text) == ";"
    assert sniff_delimiter("one column\nonly\n") == ","


def test_utf16_csv_is_read() -> None:
    data = "Date,Description,Amount\n2026-06-03,Café,-4.25\n".encode("utf-16")
    parsed = parse_statement(data, "u16.csv")
    assert parsed.table is not None and parsed.table.rows[1].cells == (
        "2026-06-03",
        "Café",
        "-4.25",
    )


def test_a_50000_line_ofx_file_parses_quickly() -> None:
    template = (FIXTURES / "sgml_chequing_cp1252.ofx").read_bytes()
    one = (
        b"<STMTTRN>\n<TRNTYPE>DEBIT\n<DTPOSTED>20260603\n<TRNAMT>-4.25\n<FITID>F%d\n"
        b"<NAME>TIM HORTONS #1234\n</STMTTRN>\n"
    )
    big = template.replace(b"<STMTTRN>", b"".join(one % i for i in range(50_000)) + b"<STMTTRN>", 1)
    started = time.perf_counter()
    lines = FileStatementSource(big, "big.ofx").fetch_lines()
    elapsed = time.perf_counter() - started
    assert len(lines) == 50_003
    assert lines[0] == RawLine(
        row=1,
        date=dt.date(2026, 6, 3),
        amount=Decimal("-4.25"),
        description="TIM HORTONS #1234",
        payee="TIM HORTONS #1234",
        fitid="F0",
    )
    assert elapsed < 20, f"{elapsed:.1f} s"
