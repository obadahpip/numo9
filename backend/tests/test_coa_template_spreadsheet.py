"""C-01-T01 — the accountant-review spreadsheet ``docs/accounting/coa_template_ca_v1.xlsx``.

The committed spreadsheet is the file the project lead and the client accountant sign off; it
must hold exactly the rows the loader creates (``coa_ca_v1.json``), so it is generated by
``tools/export_coa_template.py`` and this test fails when it is out of date. It also checks what
the reviewers need: every account with its type, sub-type, GIFI code and description, tax key,
the checks (0 unmapped GIFI), the review questions and an unsigned sign-off sheet.
"""

from __future__ import annotations

from openpyxl import load_workbook

from numo9.ledger.template import get_template
from tools import export_coa_template as export

SHEETS = ["Read me", "Template", "Tax defaults", "Checks", "Review questions", "Sign-off"]


def test_committed_spreadsheet_is_up_to_date() -> None:
    assert export.main(["--check"]) == 0


def test_spreadsheet_contents() -> None:
    book = load_workbook(export.OUTPUT, read_only=True)
    assert book.sheetnames == SHEETS
    rows = list(book["Template"].iter_rows(values_only=True))
    header, body = rows[0], rows[1:]
    assert header[:4] == ("Code", "Name", "Type", "Sub-type")
    template = get_template()
    assert [r[0] for r in body] == [a.code for a in template.accounts]
    assert all(r[7] and r[8] for r in body)  # GIFI code + description on every row
    inventory = next(r for r in body if r[0] == "1200")
    assert inventory[2:4] == ("Asset", "Inventory")
    checks = dict(r for r in book["Checks"].iter_rows(values_only=True) if r and r[0])
    assert checks["Unmapped GIFI (gap-30: must be 0)"] == 0
    assert checks["Accounts mapped to a GIFI total line (must be 0)"] == 0
    taxes = list(book["Tax defaults"].iter_rows(values_only=True))
    assert len(taxes) == 14 and taxes[9][:3] == ("ON", "HST 13 %", "purchase.ON.standard")
    sign = list(book["Sign-off"].iter_rows(values_only=True))
    assert [r[0] for r in sign[1:3]] == ["Project lead (GMA)", "Client accountant (Profitex)"]
    assert all(cell is None for cell in sign[1][1:]) and all(c is None for c in sign[2][1:])
