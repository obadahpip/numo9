"""``manage.py permcat_docs`` — generate the permission catalogue page of the docs (A-03-T16).

    python manage.py permcat_docs            # (re)write docs/reference/permission-catalogue.md
    python manage.py permcat_docs --check    # CI: fail when the committed page is out of date

The page is generated from the catalogue in code (every app's ``permissions.py``) and the system
roles' rules — never edited by hand. It lists, per module, every permission with its English and
French label, risk, scope and owner-only flag, and which of the 15 system roles give it. CI runs
``--check`` in the backend job (the page must match the code) and ``mkdocs build --strict`` in
the docs job (the page must build).
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

from django.conf import settings
from django.core.management.base import BaseCommand, CommandError, CommandParser
from django.utils import translation

from numo9.rbac.catalogue import MODULE_LABELS, MODULES, Permission, catalogue
from numo9.rbac.system_roles import SYSTEM_ROLES

DEFAULT_OUTPUT = Path(settings.BASE_DIR).parent / "docs" / "reference" / "permission-catalogue.md"

SCOPE_ORDER = ("organisation", "practice", "platform")


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def _role_names() -> dict[tuple[str, str], str]:
    with translation.override("en-ca"):
        return {(r.scope.value, r.key): str(r.name) for r in SYSTEM_ROLES}


def _granted_by(permission: Permission) -> list[str]:
    names = _role_names()
    return [
        names[(r.scope.value, r.key)]
        for r in SYSTEM_ROLES
        if permission.key in r.permission_keys(catalogue)
    ]


def render() -> str:
    permissions = list(catalogue)
    with translation.override("fr-ca"):
        french = {p.key: str(p.label) for p in permissions}
    with translation.override("en-ca"):
        english = {p.key: str(p.label) for p in permissions}
        modules = {m: str(MODULE_LABELS[m]) for m in MODULES}
    used = [m for m in MODULES if any(p.module == m for p in permissions)]
    lines: list[str] = [
        "# Permission catalogue",
        "",
        "<!-- Generated by `python manage.py permcat_docs` from the code (A-03-T16). "
        "Do not edit: change the app's permissions.py and run the command. -->",
        "",
        f"Every permission Numo9 checks — **{len(permissions)}** in "
        f"{len(used)} modules — generated from each app's `permissions.py` and the system "
        "roles' rules ([Roles and permissions](../architecture/permissions.md)). CI fails when "
        "this page is out of date.",
        "",
        "Risk: low · medium · high · critical (what misuse could do). Scope: where it is "
        "checked — organisation, practice or platform. *Owner only*: not given by broad roles.",
        "",
        "| Module | Permissions |",
        "|---|---|",
    ]
    for module in used:
        count = sum(p.module == module for p in permissions)
        anchor = f"#{module}"
        lines.append(f"| [{modules[module]}]({anchor}) | {count} |")
    for module in used:
        lines += [
            "",
            f"## {modules[module]} {{ #{module} }}",
            "",
            "| Key | Permission (en-CA) | Permission (fr-CA) | Risk | Scope "
            "| Given by system roles |",
            "|---|---|---|---|---|---|",
        ]
        for p in (p for p in permissions if p.module == module):
            owner = " *(owner only)*" if p.owner_only else ""
            roles = ", ".join(_granted_by(p)) or "—"
            lines.append(
                f"| `{p.key}` | {_cell(english[p.key])}{owner} | {_cell(french[p.key])} | "
                f"{p.risk.value} | {p.scope.value} | {_cell(roles)} |"
            )
    names = _role_names()
    lines += [
        "",
        "## System roles { #system-roles }",
        "",
        "| Scope | Role | Key | Permissions |",
        "|---|---|---|---|",
    ]
    for scope in SCOPE_ORDER:
        for role in (r for r in SYSTEM_ROLES if r.scope.value == scope):
            count = len(role.permission_keys(catalogue))
            lines.append(f"| {scope} | {names[(scope, role.key)]} | `{role.key}` | {count} |")
    return "\n".join(lines) + "\n"


class Command(BaseCommand):
    help = "Generate the permission catalogue docs page (or --check that it is up to date)."

    def add_arguments(self, parser: CommandParser) -> None:
        parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
        parser.add_argument(
            "--check", action="store_true", help="Fail when the page differs from the code."
        )

    def handle(self, *args: Any, **options: Any) -> None:
        output: Path = options["output"]
        text = render()
        if options["check"]:
            current = output.read_text(encoding="utf-8") if output.exists() else ""
            if current.replace("\r\n", "\n") != text:
                raise CommandError(
                    f"{output} is out of date with the permission catalogue. Run "
                    "`python manage.py permcat_docs` and commit the page."
                )
            self.stdout.write(f"{output.name} is up to date ({len(catalogue)} permissions).")
            return
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(text, encoding="utf-8")
        self.stdout.write(f"{len(catalogue)} permissions written to {output}")
